class CameraProcessor:
    def __init__(self, camera_id, source, model, tracker, args, required_ppe, detect_class_indices):
        self.camera_id = camera_id
        self.source = source
        self.model = model
        self.tracker = tracker
        self.args = args
        self.required_ppe = required_ppe
        self.detect_class_indices = detect_class_indices

        # Open video source
        self.cap = cv2.VideoCapture(source)
        if not self.cap.isOpened():
            raise ValueError(f"Cannot open camera source: {source}")

        # Get camera properties
        self.width = int(self.cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        self.height = int(self.cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        self.fps = self.cap.get(cv2.CAP_PROP_FPS)
        if self.fps == 0 or self.fps > 120:  # Handle invalid FPS
            self.fps = 30

    def process_frame(self):
        """Process a single frame from this camera"""
        ret, frame = self.cap.read()
        if not ret:
            return None

        # Run YOLO detection
        results = self.model.predict(
            frame,
            conf=self.args.conf,
            iou=self.args.iou,
            classes=self.detect_class_indices,
            verbose=False
        )

        dets = results[0].boxes
        detections_for_tracker = []
        ppe_items = []

        if dets is not None and len(dets) > 0:
            for i in range(len(dets)):
                xyxy = dets.xyxy[i].cpu().tolist()
                cls_id = int(dets.cls[i].cpu().item())
                conf = float(dets.conf[i].cpu().item())
                class_name = canonicalize(self.model.names.get(cls_id, ""))

                if class_name == "person":
                    w, h = xyxy[2] - xyxy[0], xyxy[3] - xyxy[1]
                    detections_for_tracker.append(([xyxy[0], xyxy[1], w, h], conf, class_name))
                else:
                    if conf >= self.args.conf:
                        ppe_items.append({"center": center_of_box(xyxy), "name": class_name})

        # Update tracker
        tracks = self.tracker.update_tracks(detections_for_tracker, frame=frame)

        # Draw detections
        for track in tracks:
            if not track.is_confirmed():
                continue

            track_id = track.track_id
            ltrb = track.to_ltrb()
            px1, py1, px2, py2 = map(int, ltrb)

            # Determine PPE status
            owned_ppe = {item["name"] for item in ppe_items if inside_bbox(item["center"], ltrb)}
            missing_items = set()
            present_items = set()

            for required_item in self.required_ppe:
                if required_item in owned_ppe:
                    present_items.add(required_item)
                elif f"no_{required_item}" in owned_ppe:
                    missing_items.add(required_item)
                else:
                    missing_items.add(required_item)

            # Draw bounding box
            color = CLR_MISS if missing_items else CLR_OK
            cv2.rectangle(frame, (px1, py1), (px2, py2), color, 2)

            # Draw PPE status
            x, y = px1, py1 - 10
            base_text = f"ID: {track_id} PPE:"
            font = cv2.FONT_HERSHEY_SIMPLEX
            scale = 0.6
            thickness = 2

            # Draw base text with background
            text_size = cv2.getTextSize(base_text, font, scale, thickness)[0]
            overlay = frame.copy()
            cv2.rectangle(overlay, (x-2, y-16), (x + text_size[0] + 4, y+6), (0,0,0), -1)
            alpha = 0.6
            frame = cv2.addWeighted(overlay, alpha, frame, 1 - alpha, 0)
            cv2.putText(frame, base_text, (x, y), font, scale, (255,255,255), thickness)

            offset_x = x + text_size[0] + 10

            # Draw individual PPE items
            for item in sorted(list(self.required_ppe)):
                if item in present_items:
                    status = "OK"
                    text_color = (0, 200, 0)
                else:
                    status = "MISSING"
                    text_color = (0, 0, 255)

                text = f" {item}:{status}"
                tsize = cv2.getTextSize(text, font, scale, thickness)[0]
                overlay = frame.copy()
                cv2.rectangle(overlay, (offset_x-2, y-16), (offset_x + tsize[0] + 4, y+6), (0,0,0), -1)
                frame = cv2.addWeighted(overlay, alpha, frame, 1 - alpha, 0)
                cv2.putText(frame, text, (offset_x, y), font, scale, text_color, thickness)
                offset_x += tsize[0] + 10

            # Log violations
            if missing_items and self.args.log:
                timestamp = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
                missing_str = ", ".join(sorted(list(missing_items)))
                log_entry = f"{timestamp} | Cam {self.camera_id} | {track_id:<9} | {missing_str}\n"
                with open(self.args.log, "a") as f:
                    f.write(log_entry)

        # Add camera label
        label_text = f"Camera {self.camera_id}"
        cv2.putText(frame, label_text, (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (255, 255, 255), 2)

        return frame

    def release(self):
        """Release camera resources"""
        self.cap.release()

