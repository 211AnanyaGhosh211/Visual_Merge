def canonicalize(name: str) -> str:
    n = name.lower().replace(" ", "_")
    for canon, synonyms in ALIASES.items():
        if n == canon or n in synonyms:
            return canon
    return n

def center_of_box(xyxy):
    x1, y1, x2, y2 = xyxy
    return (int((x1 + x2) / 2), int((y1 + y2) / 2))

def inside_bbox(point, bbox):
    px, py = point
    x1, y1, x2, y2 = bbox
    return x1 <= px <= x2 and y1 <= py <= y2

def ensure_log_file(path):
    if not Path(path).exists():
        with open(path, "w") as f:
            f.write("--- PPE VIOLATION LOG ---\n")
            f.write("Timestamp           | Camera | Person ID | Missing PPE\n")
            f.write("--------------------+--------+-----------+-----------------\n")

def parse_video_source(source):
    """Parse video source to determine if it's a file, webcam index, or RTSP URL"""
    # Check if it's a number (webcam index)
    try:
        return int(source)
    except ValueError:
        pass

    # Check if it's an RTSP/HTTP URL
    if source.startswith(('rtsp://', 'http://', 'https://')):
        return source

    # Otherwise treat as file path
    return source

def calculate_grid_layout(num_cameras):
    """Calculate optimal grid layout for multiple cameras"""
    if num_cameras == 1:
        return 1, 1
    elif num_cameras == 2:
        return 1, 2
    elif num_cameras <= 4:
        return 2, 2
    elif num_cameras <= 6:
        return 2, 3
    elif num_cameras <= 9:
        return 3, 3
    elif num_cameras <= 12:
        return 3, 4
    else:
        return 4, 4

def resize_frame_to_fit(frame, target_width, target_height):
    """Resize frame to fit target dimensions while maintaining aspect ratio"""
    h, w = frame.shape[:2]

    # Calculate scaling factor
    scale = min(target_width / w, target_height / h)

    new_w = int(w * scale)
    new_h = int(h * scale)

    # Resize frame
    resized = cv2.resize(frame, (new_w, new_h))

    # Create canvas with black background
    canvas = np.zeros((target_height, target_width, 3), dtype=np.uint8)

    # Center the resized frame on canvas
    y_offset = (target_height - new_h) // 2
    x_offset = (target_width - new_w) // 2

    canvas[y_offset:y_offset+new_h, x_offset:x_offset+new_w] = resized

    return canvas

