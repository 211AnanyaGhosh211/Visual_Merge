def main(args):
    if args.log:
        ensure_log_file(args.log)

    # Load model
    try:
        model = YOLO(args.model)
    except Exception as e:
        print(f"Error loading model: {e}")
        return

    # Parse video sources
    video_sources = []
    if args.cameras:
        for source in args.cameras:
            video_sources.append(parse_video_source(source))
    else:
        video_sources.append(parse_video_source(args.video))

    num_cameras = len(video_sources)
    print(f"Processing {num_cameras} camera(s)")

    # Setup PPE detection classes
    detect_classes_names = set()
    required_ppe = set()

    if args.classes:
        print(f"User specified classes: {args.classes}")
        user_ppe_types = set()
        for cls_name in args.classes:
            canon_name = canonicalize(cls_name)
            if canon_name.startswith("no_"):
                user_ppe_types.add(canon_name[3:])
            else:
                user_ppe_types.add(canon_name)

        required_ppe = user_ppe_types
        print(f"Required PPE for all zones set to: {required_ppe}")

        for ppe_type in required_ppe:
            detect_classes_names.add(ppe_type)
            detect_classes_names.add(f"no_{ppe_type}")
    else:
        print("No specific classes provided. Using fallback full PPE requirements.")
        required_ppe = DEFAULT_REQUIRED_PPE
        for ppe_type in required_ppe:
            detect_classes_names.add(ppe_type)
            detect_classes_names.add(f"no_{ppe_type}")

    detect_classes_names.add("person")

    # Map class names to indices
    detect_class_indices = []
    model_class_map = {canonicalize(name): idx for idx, name in model.names.items()}
    for name in detect_classes_names:
        if name in model_class_map:
            detect_class_indices.append(model_class_map[name])

    print(f"Model will detect the following classes: {[model.names[i] for i in detect_class_indices]}")

    # Initialize camera processors
    camera_processors = []
    for i, source in enumerate(video_sources):
        try:
            tracker = DeepSort(max_age=70, n_init=3)
            processor = CameraProcessor(
                camera_id=i+1,
                source=source,
                model=model,
                tracker=tracker,
                args=args,
                required_ppe=required_ppe,
                detect_class_indices=detect_class_indices
            )
            camera_processors.append(processor)
            print(f"Camera {i+1} initialized: {source}")
        except Exception as e:
            print(f"Error initializing camera {i+1} ({source}): {e}")

    if not camera_processors:
        print("No cameras could be initialized. Exiting.")
        return

    # Calculate grid layout
    rows, cols = calculate_grid_layout(len(camera_processors))

    # Use first camera's properties as base for output
    output_width = args.output_width if args.output_width else 1920
    output_height = args.output_height if args.output_height else 1080
    output_fps = camera_processors[0].fps

    # Calculate cell dimensions
    cell_width = output_width // cols
    cell_height = output_height // rows

    # Setup video writer
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(args.output, fourcc, output_fps, (output_width, output_height))

    print(f"Output: {output_width}x{output_height} @ {output_fps} FPS")
    print(f"Grid layout: {rows}x{cols}")
    print("Processing started. Press 'q' to quit.")

    # Main processing loop
    frame_count = 0
    while True:
        # Create blank canvas for combined output
        combined_frame = np.zeros((output_height, output_width, 3), dtype=np.uint8)

        all_frames_valid = True

        # Process each camera
        for idx, processor in enumerate(camera_processors):
            frame = processor.process_frame()

            if frame is None:
                all_frames_valid = False
                break

            # Calculate position in grid
            row = idx // cols
            col = idx % cols

            # Resize frame to fit cell
            resized_frame = resize_frame_to_fit(frame, cell_width, cell_height)

            # Place frame in grid
            y_start = row * cell_height
            x_start = col * cell_width
            combined_frame[y_start:y_start+cell_height, x_start:x_start+cell_width] = resized_frame

        if not all_frames_valid:
            print("One or more cameras stopped. Ending processing.")
            break

        # Display and write output
        cv2_imshow(combined_frame)
        out.write(combined_frame)

        frame_count += 1
        if frame_count % 30 == 0:
            print(f"Processed {frame_count} frames...")

        if cv2.waitKey(1) & 0xFF == ord('q'):
            break

    # Cleanup
    for processor in camera_processors:
        processor.release()
    out.release()
    cv2.destroyAllWindows()

    print(f"Processing complete. Output video saved to {args.output}")
    print(f"Total frames processed: {frame_count}")


